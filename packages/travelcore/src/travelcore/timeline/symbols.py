_DEFAULT_MARKUP = TRANSPORT_SYMBOLS[-1].markup
_BY_KEY = {item.key: item for item in TRANSPORT_SYMBOLS}


def symbol_label(key: str) -> str:
    item = _BY_KEY.get(key)
    return item.label if item is not None else key


def symbol_inner_svg(key: str, color: str) -> str:
    item = _BY_KEY.get(key)
    markup = item.markup if item is not None else _DEFAULT_MARKUP
    return markup.replace(_FILL, f'fill="{color}"').replace(_COLOR, color)


def symbol_badge_svg(
    key: str,
    *,
    size: int = 36,
    icon_color: str = "#ffffff",
    disc: str = "#000000",
) -> str:
    """Black disc with a white pictogram facing right, as on the map."""

    inner = symbol_inner_svg(key, icon_color)
    inset = size * 6 / 36
    scale = (size - 2 * inset) / ICON_VIEWBOX
    mid = size / 2
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 {size} {size}">'
        f'<circle cx="{mid}" cy="{mid}" r="{mid}" fill="{disc}"/>'
        f'<g transform="translate({inset} {inset}) scale({scale})">{inner}</g>'
        f"</svg>"
    )


def stay_symbol_svg_js(*, indent: str = "    ") -> str:
    """Leaflet helper `staySymbolSvg(symbol, color)` from the same catalog."""

    pad = indent
    inner = indent + "  "
    lines = [
        f"{pad}function staySymbolSvg(symbol, color) {{",
        f"{inner}var fill = 'fill=\"' + color + '\"';",
    ]
    for item in TRANSPORT_SYMBOLS:
        js_markup = item.markup.replace(_FILL, "' + fill + '").replace(_COLOR, "' + color + '")
        lines.append(f"{inner}if (symbol === '{item.key}') {{")
        lines.append(f"{inner}  return '{js_markup}';")
        lines.append(f"{inner}}}")
    lines.append(
        f"{inner}return '{_DEFAULT_MARKUP.replace(_FILL, "' + fill + '").replace(_COLOR, "' + color + '")}';"
    )
    lines.append(f"{pad}}}")
    return "\n".join(lines)
